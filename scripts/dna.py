#!/usr/bin/env python3
"""dna — the ledger for long, multi-compaction agent runs.

  dna.py init "goal" [--req "requirement" ...] [--judge "command"]
  dna.py log --hyp H --change C --result R --keep|--revert [--sig ERRSIG] [--metric N] [--parent ID]
  dna.py state                 regenerate the derived half of STATE.md from the journal
  dna.py branch                print the active branch (what the post-compaction hook injects)
  dna.py lesson --type fact|procedure|rule|role --trigger T --evidence E --expect X --text "lesson"
  dna.py observe ID --effect "what actually happened" [--helped|--hurt]
  dna.py rollback ID --why "reason"
  dna.py audit                 completion audit: every requirement needs evidence, judge must pass
  dna.py judge                 run the frozen judge command and log its result

The journal (.dna/JOURNAL.jsonl) is append-only and is the source of truth."""
import argparse, datetime, json, os, re, subprocess, sys
sys.dont_write_bytecode = True

ROOT = os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
L = os.path.join(ROOT, ".dna")
J = os.path.join(L, "JOURNAL.jsonl")
META = os.path.join(L, "meta.json")
STATE = os.path.join(L, "STATE.md")
LESSONS = os.path.join(L, "LESSONS.md")
DERIVED = "<!-- derived: regenerated by dna.py state; edit above this line -->"


def now():
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def entries():
    if not os.path.exists(J):
        return []
    out = []
    for line in open(J):
        line = line.strip()
        if line:
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    return out


def append(e):
    e.setdefault("at", now())
    e["id"] = e.get("id") or f"{e['type'][0]}{len(entries()) + 1:04d}"
    with open(J, "a") as f:
        f.write(json.dumps(e, ensure_ascii=False) + "\n")
    return e


def meta():
    return json.load(open(META)) if os.path.exists(META) else {}


def norm_sig(s):
    """Error signature: strip numbers, paths and hex so the same failure matches across runs."""
    s = (s or "").lower()
    s = re.sub(r"0x[0-9a-f]+|[0-9a-f]{8,}", "#", s)
    s = re.sub(r"(/[\w.\-]+)+", "/path", s)
    s = re.sub(r"\d+", "n", s)
    return re.sub(r"\s+", " ", s).strip()[:120]


def cmd_init(a):
    os.makedirs(os.path.join(L, "checkpoints"), exist_ok=True)
    if os.path.exists(META) and not a.force:
        sys.exit(".dna already initialized (use --force to reset the goal)")
    m = {"goal": a.goal, "requirements": a.req or [], "judge": a.judge or "", "created": now()}
    json.dump(m, open(META, "w"), indent=1)
    if not os.path.exists(STATE):
        open(STATE, "w").write(
            f"# State\n\n## Goal\n{a.goal}\n\n## Outcome this serves\n(answer question 1)\n\n## Invariants\n(answer question 4)\n\n"
            f"## Judge\n{a.judge or '(answer question 6)'}\n\n## In progress\n\n## Next\n\n## Decisions\n\n{DERIVED}\n")
    if not os.path.exists(LESSONS):
        open(LESSONS, "w").write("# Lessons\n\nOne line per lesson, newest last. `dna.py lesson` appends; `dna.py rollback` strikes.\n\n")
    append({"type": "init", "goal": a.goal, "requirements": m["requirements"], "judge": m["judge"]})
    gi = os.path.join(ROOT, ".gitignore")
    try:
        txt = open(gi).read() if os.path.exists(gi) else ""
        if ".dna/checkpoints" not in txt:
            open(gi, "a").write("\n.dna/checkpoints/\n.dna/.model\n")
    except OSError:
        pass
    cmd_state(a)
    print(f"initialized .dna for: {a.goal}")


def cmd_log(a):
    es = [e for e in entries() if e["type"] == "step"]
    sig = norm_sig(a.sig) if a.sig else ""
    kept = [x for x in es if x.get("keep")]
    base = kept[-1]["id"] if kept else (es[-1]["id"] if es else None)
    e = append({"type": "step", "parent": a.parent or base, "hyp": a.hyp, "change": a.change,
                "result": a.result, "keep": bool(a.keep), "metric": a.metric, "sig": sig})
    warn = ""
    if sig and es and es[-1].get("sig") == sig and not es[-1].get("keep"):
        warn = (f"REDESIGN: same error signature twice in a row ({sig!r}, steps {es[-1]['id']} and {e['id']}). "
                "Stop patching; return to the last kept step and change the approach.")
        append({"type": "flag", "flag": "repeat-signature", "sig": sig, "steps": [es[-1]["id"], e["id"]]})
    cmd_state(a, quiet=True)
    print(f"logged {e['id']}" + (f"\n{warn}" if warn else ""))


def derived_block():
    es = entries()
    m = meta()
    steps = [e for e in es if e["type"] == "step"]
    kept = [e for e in steps if e.get("keep")]
    sigs = {}
    for e in steps:
        if e.get("sig"):
            sigs[e["sig"]] = sigs.get(e["sig"], 0) + 1
    lessons = [e for e in es if e["type"] == "lesson"]
    rolled = {e["target"] for e in es if e["type"] == "rollback"}
    best = None
    for e in kept:
        if isinstance(e.get("metric"), (int, float)) and (best is None or e["metric"] > best["metric"]):
            best = e
    judges = [e for e in es if e["type"] == "judge"]
    lines = [DERIVED, "", "## From the journal",
             f"- Steps: {len(steps)} ({len(kept)} kept, {len(steps) - len(kept)} reverted)",
             f"- Last kept step: {kept[-1]['id'] + ' — ' + kept[-1]['change'][:90] if kept else 'none'}",
             f"- Best metric: {best['metric']} at {best['id']}" if best else "- Best metric: none recorded",
             f"- Last judge run: {judges[-1]['verdict']} at {judges[-1]['at']}" if judges else "- Last judge run: never"]
    rep = [f"{s!r} ×{n}" for s, n in sorted(sigs.items(), key=lambda x: -x[1]) if n > 1]
    lines.append("- Repeated error signatures: " + ("; ".join(rep[:5]) if rep else "none"))
    act = [l for l in lessons if l["id"] not in rolled]
    lines.append(f"- Lessons active: {len(act)}, rolled back: {len(rolled)}")
    lines.append(f"- Requirements: {len(m.get('requirements', []))} (check with dna.py audit)")
    return "\n".join(lines) + "\n"


def cmd_state(a=None, quiet=False):
    if not os.path.exists(STATE):
        return
    txt = open(STATE).read()
    head = txt.split(DERIVED)[0].rstrip() + "\n\n"
    open(STATE, "w").write(head + derived_block())
    if not quiet:
        print(open(STATE).read())


def active_branch(k_anc=3, k_sib=3):
    es = entries()
    steps = [e for e in es if e["type"] == "step"]
    if not steps:
        return "No steps logged yet."
    by = {e["id"]: e for e in steps}
    cur = steps[-1]
    chain, p = [cur], cur.get("parent")
    while p in by and len(chain) <= k_anc:
        chain.append(by[p]); p = by[p].get("parent")
    sibs = [e for e in steps if e.get("parent") == cur.get("parent") and e["id"] != cur["id"]][-k_sib:]
    same = [e for e in steps if cur.get("sig") and e.get("sig") == cur["sig"] and e["id"] != cur["id"]][-3:]
    fmt = lambda e: f"  {e['id']} [{'kept' if e.get('keep') else 'reverted'}] {e['hyp'][:70]} → {e['result'][:70]}" + (f" (sig: {e['sig']})" if e.get("sig") else "")
    out = ["Current step and ancestors:"] + [fmt(e) for e in chain]
    if sibs: out += ["Sibling attempts from the same parent:"] + [fmt(e) for e in sibs]
    if same: out += ["Earlier attempts that failed the same way:"] + [fmt(e) for e in same]
    flags = [e for e in es if e["type"] == "flag"][-2:]
    if flags: out += ["Flags:"] + [f"  {f['flag']}: {f.get('sig', '')} {f.get('steps', '')}" for f in flags]
    return "\n".join(out)


def cmd_branch(a):
    print(active_branch())


def cmd_lesson(a):
    e = append({"type": "lesson", "kind": a.type, "trigger": a.trigger, "evidence": a.evidence, "expect": a.expect, "text": a.text})
    with open(LESSONS, "a") as f:
        f.write(f"- [{e['id']}] ({a.type}) {a.text} — trigger: {a.trigger}; evidence: {a.evidence}; expect: {a.expect}\n")
    cmd_state(a, quiet=True)
    print(f"lesson {e['id']} recorded. Where it belongs: " + {"fact": ".dna/LESSONS.md (done)", "procedure": "a skill",
          "rule": "one line in this project's CLAUDE.md", "role": "a subagent definition"}[a.type])


def cmd_observe(a):
    append({"type": "observe", "target": a.id, "effect": a.effect, "helped": a.helped, "hurt": a.hurt})
    cmd_state(a, quiet=True)
    print(f"observation logged for {a.id}" + ("; consider dna.py rollback" if a.hurt else ""))


def cmd_rollback(a):
    append({"type": "rollback", "target": a.id, "why": a.why})
    if os.path.exists(LESSONS):
        txt = open(LESSONS).read().replace(f"- [{a.id}]", f"- ~~[{a.id}]")
        open(LESSONS, "w").write(txt.rstrip("\n") + ("" if f"rolled back {a.id}" in txt else f"\n  - rolled back {a.id}: {a.why}") + "\n")
    cmd_state(a, quiet=True)
    print(f"rolled back {a.id}")


def run_judge():
    m = meta()
    if not m.get("judge"):
        return None, "no judge command set (dna.py init --judge, or edit .dna/meta.json)"
    try:
        p = subprocess.run(m["judge"], shell=True, cwd=ROOT, capture_output=True, text=True, timeout=1800)
        out = (p.stdout + p.stderr)[-6000:]
        return p.returncode == 0, out
    except subprocess.TimeoutExpired:
        return False, "judge timed out"


def cmd_judge(a):
    ok, out = run_judge()
    if ok is None:
        sys.exit(out)
    append({"type": "judge", "verdict": "PASS" if ok else "FAIL", "tail": out[-800:]})
    cmd_state(a, quiet=True)
    print(("PASS" if ok else "FAIL") + "\n" + out[-2000:])


def cmd_audit(a):
    m = meta()
    es = entries()
    reqs = m.get("requirements", [])
    ev = {e["req"]: e for e in es if e["type"] == "evidence"}
    if a.req is not None:
        if a.req >= len(reqs): sys.exit("no such requirement")
        append({"type": "evidence", "req": a.req, "evidence": a.evidence or ""})
        print(f"evidence recorded for requirement {a.req}"); return
    ok, out = run_judge()
    if ok is not None:
        append({"type": "judge", "verdict": "PASS" if ok else "FAIL", "tail": out[-800:]})
    print(f"Goal: {m.get('goal', '(none)')}\n")
    missing = 0
    for i, r in enumerate(reqs):
        has = i in ev and ev[i]["evidence"].strip()
        missing += 0 if has else 1
        print(f"  [{'x' if has else ' '}] {i}. {r}" + (f"\n        evidence: {ev[i]['evidence'][:160]}" if has else "\n        no evidence: dna.py audit --req %d --evidence '...'" % i))
    if not reqs:
        print("  No requirements were set. Write them into .dna/meta.json so done can be checked.")
    jv = "not set" if ok is None else ("PASS" if ok else "FAIL")
    print(f"\nJudge: {jv}")
    done = reqs and missing == 0 and ok is not False
    print("VERDICT: " + ("DONE" if done else "NOT DONE") + ("" if done else f" ({missing} requirement(s) without evidence{', judge failing' if ok is False else ''})"))
    print("Also report: assumptions you made, constants you changed.")
    cmd_state(a, quiet=True)
    sys.exit(0 if done else 1)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    s = p.add_subparsers(dest="cmd", required=True)
    i = s.add_parser("init"); i.add_argument("goal"); i.add_argument("--req", action="append"); i.add_argument("--judge"); i.add_argument("--force", action="store_true")
    g = s.add_parser("log"); g.add_argument("--hyp", required=True); g.add_argument("--change", required=True); g.add_argument("--result", required=True)
    k = g.add_mutually_exclusive_group(required=True); k.add_argument("--keep", action="store_true"); k.add_argument("--revert", action="store_true")
    g.add_argument("--sig"); g.add_argument("--metric", type=float); g.add_argument("--parent")
    s.add_parser("state"); s.add_parser("branch"); s.add_parser("judge")
    le = s.add_parser("lesson"); le.add_argument("--type", choices=["fact", "procedure", "rule", "role"], required=True)
    for f in ("trigger", "evidence", "expect", "text"): le.add_argument("--" + f, required=True)
    o = s.add_parser("observe"); o.add_argument("id"); o.add_argument("--effect", required=True); o.add_argument("--helped", action="store_true"); o.add_argument("--hurt", action="store_true")
    r = s.add_parser("rollback"); r.add_argument("id"); r.add_argument("--why", required=True)
    au = s.add_parser("audit"); au.add_argument("--req", type=int); au.add_argument("--evidence")
    a = p.parse_args()
    if a.cmd != "init" and not os.path.isdir(L):
        sys.exit("no .dna/ here; run dna.py init \"goal\" first")
    {"init": cmd_init, "log": cmd_log, "state": cmd_state, "branch": cmd_branch, "lesson": cmd_lesson, "observe": cmd_observe,
     "rollback": cmd_rollback, "audit": cmd_audit, "judge": cmd_judge}[a.cmd](a)


if __name__ == "__main__":
    main()
